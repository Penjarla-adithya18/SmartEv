const STORAGE_KEY = 'smartev_owner_added_stations'

// Get all owner added stations (Supabase -> localStorage -> INITIAL_BHIMAVARAM_STATIONS)
export async function getOwnerAddedStations(): Promise<EVStation[]> {
  // 1. Try Supabase
  const supabaseStations = await getStationsFromSupabase()
  if (supabaseStations && supabaseStations.length > 0) {
    return supabaseStations
  }

  // 2. Fallback to localStorage on browser side
  if (typeof window !== 'undefined') {
    try {
      const saved = localStorage.getItem(STORAGE_KEY)
      if (saved) {
        const parsed = JSON.parse(saved)
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed
        }
      }
    } catch (e) {
      console.warn('Failed reading owner stations from localStorage', e)
    }
  }

  return INITIAL_STATIONS
}

// Add a new owner station
export async function addOwnerStation(stationData: Partial<EVStation>): Promise<EVStation> {
  const newStation: EVStation = {
    id: stationData.id || 'bv-owner-' + Date.now(),
    slug:
      stationData.slug ||
      (stationData.name || 'bhimavaram-station').toLowerCase().replace(/[^a-z0-9]+/g, '-') +
        '-' +
        Math.floor(Math.random() * 1000),
    name: stationData.name || 'New Owner Charging Station',
    latitude: Number(stationData.latitude) || 16.5449,
    longitude: Number(stationData.longitude) || 81.5212,
    address: stationData.address || 'Bhimavaram, Andhra Pradesh',
    city: stationData.city || 'Bhimavaram',
    rating: Number(stationData.rating) || 5.0,
    totalPorts: Number(stationData.totalPorts) || 4,
    availablePorts: Number(stationData.availablePorts) || 4,
    pricePerKwh: Number(stationData.pricePerKwh) || 12,
    powerKw: Number(stationData.powerKw) || 120,
    fastCharging: Boolean(stationData.fastCharging ?? true),
    connectors: stationData.connectors || ['CCS2', 'Type 2'],
    status: stationData.status || 'available',
    waitMinutes: Number(stationData.waitMinutes) || 0,
    aiScore: Number(stationData.aiScore) || 95,
    image:
      stationData.image ||
      'https://images.unsplash.com/photo-1563720223185-11003d516935?w=800&auto=format&fit=crop&q=60',
    operatingHours: stationData.operatingHours || '24/7 Open',
    network: stationData.network || 'Owner Direct Station',
  }

  // 1. Try Supabase insertion
  const savedSupabase = await saveStationToSupabase(newStation)
  const resultStation = savedSupabase || newStation

  // 2. Update local storage
  if (typeof window !== 'undefined') {
    try {
      const existing = await getOwnerAddedStations()
      const updated = [resultStation, ...existing.filter((s) => s.id !== resultStation.id)]
      localStorage.setItem(STORAGE_KEY, JSON.stringify(updated))
    } catch (e) {
      console.warn('LocalStorage save error', e)
    }
  }

  return resultStation
}

export function getStationBySlug(slug: string): EVStation | undefined {
  const decoded = decodeURIComponent(slug).toLowerCase().trim()
  return INITIAL_STATIONS.find(
    (s) =>
      s.slug.toLowerCase() === decoded ||
      s.id.toLowerCase() === decoded ||
      s.name.toLowerCase().replace(/[^a-z0-9]+/g, '-') === decoded
  )
}

